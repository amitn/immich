export const WINE_LEXICON: LexiconEntry[] = [
  ...RED_GRAPES.map((name): LexiconEntry => ({ kind: 'grape', name, color: 'red' })),
  ...WHITE_GRAPES.map((name): LexiconEntry => ({ kind: 'grape', name, color: 'white' })),
  ...STYLES.map(([name, type]): LexiconEntry => ({ kind: 'style', name, ...(type && { type }) })),
  ...REGIONS.map(([name, names]): LexiconEntry => ({ kind: 'region', name, ...(names && { names }) })),
  ...PREFIXES.map((name): LexiconEntry => ({ kind: 'prefix', name })),
  ...SUFFIXES.map((name): LexiconEntry => ({ kind: 'suffix', name })),
];

/** "Spätlese" → "spatlese", "Mosel-Saar-Ruwer" → "mosel saar ruwer" */
export const normalizeWords = (text: string) =>
  text
    .normalize('NFD')
    .replaceAll(/\p{Diacritic}/gu, '')
    .replaceAll('ß', 'ss')
    .toLowerCase()
    .replaceAll(/[^\p{L}\d]+/gu, ' ')
    .trim();

/** the lexicon by normalized words, longest first, so that "Pinot Noir" is found before "Noir" and "Mosel-Saar-Ruwer" before "Mosel" */
export const LEXICON_WORDS = WINE_LEXICON.map((entry) => ({ ...entry, words: normalizeWords(entry.name).split(' ') }))
  .filter((entry, index, all) => all.findIndex((other) => other.words.join(' ') === entry.words.join(' ')) === index)
  .toSorted((a, b) => b.words.join(' ').length - a.words.join(' ').length);

