/**
 * The words of wine labels (and of beer and cider labels): grapes, styles and quality levels, regions and
 * appellations, and the words that mark the name of a producer ("Weingut", "Domaine", "Winery"), each with its
 * canonical spelling. Matched without accents and case, so OCR's "SPATLESE" is "Spätlese".
 */

export type LexiconKind = 'grape' | 'style' | 'region' | 'prefix' | 'suffix';

export type LexiconEntry = {
  kind: LexiconKind;
  /** the canonical spelling, e.g. Spätlese */
  name: string;
  /** a region whose name is the name of its wines (Mercurey, Pessac-Léognan, Chablis), not only where they come from */
  names?: boolean;
  /** red or white, for a grape */
  color?: 'red' | 'white';
  /** the kind of drink a style word says, e.g. Sparkling for Brut */
  type?: WineType;
};

export type WineType = 'Red' | 'White' | 'Rosé' | 'Sparkling' | 'Sweet' | 'Fortified' | 'Beer' | 'Cider';

